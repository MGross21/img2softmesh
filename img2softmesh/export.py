"""Writers: OBJ (+MTL) and a MuJoCo scene (built with MjSpec) with the cloth as a textured flex."""

from pathlib import Path

import mujoco
import numpy as np


def write_obj(path, verts, tris, uvs=None, texture="texture.png"):
    """uvs: per-vertex, v down (as flex texcoords); written v up."""
    path = Path(path)
    lines = ["o cloth"]
    if uvs is not None:
        mtl = path.with_suffix(".mtl")
        mtl.write_text(f"newmtl cloth\nKd 1 1 1\nKs 0 0 0\nmap_Kd {texture}\n")
        lines = [f"mtllib {mtl.name}", "o cloth", "usemtl cloth"]
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in verts]
    if uvs is not None:
        lines += [f"vt {u:.6f} {1 - v:.6f}" for u, v in uvs]
        # one uv per vertex, so v and vt share indices
        lines += ["f " + " ".join(f"{i + 1}/{i + 1}" for i in t) for t in tris]
    else:
        lines += ["f " + " ".join(str(i + 1) for i in t) for t in tris]
    path.write_text("\n".join(lines) + "\n")


ELASTIC2D = {"none": 0, "bend": 1, "stretch": 2, "both": 3}
SELFCOLLIDE = {"none": mujoco.mjtFlexSelf.mjFLEXSELF_NONE, "auto": mujoco.mjtFlexSelf.mjFLEXSELF_AUTO}


def _material(spec, name, texture):
    tex = spec.add_texture(name=name, type=mujoco.mjtTexture.mjTEXTURE_2D, file=texture,
                           colorspace=mujoco.mjtColorSpace.mjCOLORSPACE_AUTO)
    mat = spec.add_material(name=name, specular=0, shininess=0)
    mat.textures[mujoco.mjtTextureRole.mjTEXROLE_RGB] = tex.name


def build_scene(out_dir, *, name, kind, preset, mass, table, verts, tris, uv, back, grippers, selfcollide="none",
                back_texture=None):
    """MjSpec of the demo scene: table (half-extents x, y, z), cloth flex from the fabric preset, scripted grippers.

    verts/tris: cloth mesh (world frame), uv: per-vertex texcoords (v down) into texture.png.
    back: per-triangle bool, True on the back layer; drawn with back_texture (same uv) if given.
    verts/tris/uv/back are numpy arrays.
    grippers: [(position, cloth vertex ids it holds), ...]
    """
    p = preset
    spec = mujoco.MjSpec()
    spec.modelname = f"img2softmesh-{name}"
    spec.comment = f"generated by img2softmesh; kind={kind}"
    spec.modelfiledir = str(out_dir)
    spec.memory = 256 << 20
    o = spec.option
    # contact stiffness is capped at 2 * timestep: cloth-on-cloth contact needs the small step to keep layers apart
    o.timestep = 0.002 if p.layers == 2 or selfcollide != "none" else 0.004
    o.tolerance = 1e-3
    o.solver, o.integrator = mujoco.mjtSolver.mjSOL_CG, mujoco.mjtIntegrator.mjINT_DISCRETE
    v = spec.visual
    v.headlight.ambient, v.headlight.diffuse, v.headlight.specular = [.45] * 3, [.55] * 3, [0] * 3
    v.global_.offwidth, v.global_.offheight = 1280, 960
    v.quality.shadowsize = 4096

    _material(spec, "cloth", "texture.png")
    if back_texture:
        _material(spec, "cloth_back", back_texture)
    grid = spec.add_texture(name="grid", type=mujoco.mjtTexture.mjTEXTURE_2D,
                            builtin=mujoco.mjtBuiltin.mjBUILTIN_CHECKER, rgb1=[.32, .34, .36], rgb2=[.26, .28, .30],
                            width=512, height=512)
    floor = spec.add_material(name="grid", texrepeat=[8, 8])
    floor.textures[mujoco.mjtTextureRole.mjTEXROLE_RGB] = grid.name

    world = spec.worldbody
    world.add_light(pos=[0, -1, 3], dir=[0, .3, -1], type=mujoco.mjtLightType.mjLIGHT_DIRECTIONAL, diffuse=[.4] * 3)
    world.add_geom(name="floor", type=mujoco.mjtGeom.mjGEOM_PLANE, size=[0, 0, .05], material="grid")
    world.add_geom(name="table", type=mujoco.mjtGeom.mjGEOM_BOX, pos=[0, 0, table[2]], size=list(table),
                   rgba=[.62, .52, .42, 1])

    # scripted grippers: mocap bodies, declared before the cloth (they couple to it through the grasp equalities)
    for g, (pos, _) in enumerate(grippers):
        world.add_body(name=f"gripper{g}", mocap=True, pos=list(pos)).add_geom(
            type=mujoco.mjtGeom.mjGEOM_SPHERE, size=[max(2.5 * p.radius, 0.01)], rgba=[1, .35, .2, 1],
            contype=0, conaffinity=0)

    # cloth: vertex bodies are named cloth_<i>; contact shell is 2 * radius thick (drawn as-is for one layer)
    mesh = spec.add_mesh(name="cloth", uservert=np.asarray(verts, float).ravel(), userface=np.asarray(tris).ravel(),
                         inertia=mujoco.mjtMeshInertia.mjMESH_INERTIA_SHELL)
    f = world.make_flex(name="cloth", dim=2, mesh="cloth", radius=p.radius, mass=mass, equality=int(p.edge_equality),
                        elastic2d=ELASTIC2D[p.elastic2d])
    spec.delete(mesh)  # only the flex's source, not a model asset
    f.young, f.poisson, f.thickness, f.damping = p.young, p.poisson, p.thickness, p.damping
    f.stressyield = [0, p.crease]  # bending yield strain: creases stay in; stretching stays elastic
    f.selfcollide = SELFCOLLIDE[selfcollide]
    f.condim, f.friction, f.solref = 3, [0.9, 0.005, 0.0001], [2 * o.timestep, 1]  # stiffest contact it allows
    f.texcoord = np.asarray(uv, float).ravel()
    f.material = ["cloth"]
    f.rgba = [1, 1, 1, 1]  # the default grey would tint the texture
    if back.any():
        # two layers share the seam vertices, so smooth flex normals there point sideways and darken the rim:
        # draw each layer as its own skin (own copy of the seam) and hide the flex
        f.group = 3
        for name, side, mat in (("front", ~back, "cloth"), ("back", back, "cloth_back" if back_texture else "cloth")):
            used, faces = np.unique(tris[side], return_inverse=True)
            spec.add_skin(name=f"cloth_{name}", material=mat, inflate=p.radius,
                          vert=verts[used].ravel(), texcoord=uv[used].ravel(), face=faces.ravel(),
                          bodyname=[f"cloth_{i}" for i in used], bindpos=verts[used].ravel(),
                          bindquat=np.tile([1.0, 0, 0, 0], len(used)), vertid=[[j] for j in range(len(used))],
                          vertweight=[[1.0]] * len(used))

    # grasp<g>_*: attach a patch of cloth vertices to gripper<g>; off until the demo grabs
    for g, (_, ids) in enumerate(grippers):
        for i, vid in enumerate(ids):
            eq = spec.add_equality(name=f"grasp{g}_{i}", type=mujoco.mjtEq.mjEQ_CONNECT,
                                   objtype=mujoco.mjtObj.mjOBJ_BODY, name1=f"cloth_{vid}", name2=f"gripper{g}",
                                   active=False)
            eq.data[:6] = 0  # anchor at the vertex itself
    return spec


def write_scene(path, **kw):
    """Build the scene next to its assets, check that it compiles, write it as MJCF."""
    path = Path(path)
    spec = build_scene(path.parent, **kw)
    spec.compile()
    path.write_text(spec.to_xml())
